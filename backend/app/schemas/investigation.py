"""Investigation Pydantic schemas for AI-assisted incident analysis."""

import uuid
from datetime import datetime
from typing import Optional, List, Literal
from pydantic import BaseModel, Field, ConfigDict

ConfidenceLevel = Literal["low", "medium", "high"]
InvestigationStatus = Literal["success", "not_configured", "insufficient_evidence", "error"]
AnalysisDepth = Literal["quick", "standard", "deep"]
StepType = Literal["immediate_check", "inspect_frame", "collect_logs", "reproduction", "diagnostic_query"]


class InvestigationRequest(BaseModel):
    """Optional configuration for the investigation request."""
    analysis_depth: AnalysisDepth = Field(
        default="standard",
        description="Depth of the investigation: quick, standard, or deep",
        example="standard",
    )


class ExecutiveSummary(BaseModel):
    """Concise synthesis of incident nature, impact, and certainty."""
    summary: str = Field(..., description="Short explanation of what failed.")
    affected_component: Optional[str] = Field(
        None, description="Component, service, endpoint, or operation affected."
    )
    evidence_synthesis: str = Field(
        ..., description="What the available collected evidence directly suggests."
    )
    certainty_assessment: str = Field(
        ..., description="Evaluation of how certain the conclusion is based on evidence."
    )


class ObservedFact(BaseModel):
    """Fact directly supported by collected evidence, with references."""
    fact: str = Field(..., description="Observed fact supported by data.")
    evidence_reference: Optional[str] = Field(
        None, description="Reference ID (e.g. EV-1) or timestamp of supporting event."
    )
    category: str = Field(
        default="general",
        description="Category: exception, stack_frame, endpoint, metric, or pattern.",
    )


class LikelyCause(BaseModel):
    """Ranked hypothesis regarding potential root cause."""
    rank: int = Field(..., ge=1, le=3, description="Rank from 1 to 3.")
    title: str = Field(..., description="Short title of the hypothesis.")
    explanation: str = Field(..., description="Detailed explanation of the hypothesis.")
    confidence: ConfidenceLevel = Field(
        ..., description="Confidence label: low, medium, or high."
    )
    supporting_evidence: List[str] = Field(
        default_factory=list, description="List of evidence reference IDs supporting this hypothesis."
    )
    missing_or_contradictory_evidence: Optional[str] = Field(
        None, description="Evidence that is missing or contradicts this hypothesis."
    )
    plausibility_rationale: str = Field(
        ..., description="Short explanation of why this hypothesis is plausible."
    )


class DebuggingStep(BaseModel):
    """Prioritized diagnostic or remediation action."""
    priority: int = Field(..., ge=1, description="Priority order (1 being highest).")
    action: str = Field(..., description="Actionable step to perform.")
    target: Optional[str] = Field(
        None, description="Specific file, stack frame, metric, or query target."
    )
    step_type: StepType = Field(
        default="immediate_check",
        description="Type: immediate_check, inspect_frame, collect_logs, reproduction, or diagnostic_query.",
    )


class InvestigationReport(BaseModel):
    """Structured incident investigation report generated by LLM or deterministic fallback."""
    executive_summary: ExecutiveSummary
    observed_facts: List[ObservedFact] = Field(default_factory=list)
    likely_causes: List[LikelyCause] = Field(default_factory=list)
    recommended_steps: List[DebuggingStep] = Field(default_factory=list)
    missing_evidence: List[str] = Field(default_factory=list)
    limitations: str = Field(
        ..., description="Description of evidence gaps and inherent uncertainty."
    )


class InvestigationReportResponse(BaseModel):
    """Public API response returned to the frontend."""
    status: InvestigationStatus
    issue_id: uuid.UUID
    project_id: uuid.UUID
    generated_at: datetime
    provider: str
    model: str
    is_ai_generated: bool = Field(
        ..., description="True if generated by an LLM, False if rule-based deterministic fallback."
    )
    report: Optional[InvestigationReport] = None
    warnings: List[str] = Field(default_factory=list)
    error_detail: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)
